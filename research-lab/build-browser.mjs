// A single module binds the executed browser algorithm to its source hash, avoiding
// a second fetch racing a deploy or a cached dependency. No runtime dependencies.
import {readFileSync,writeFileSync} from 'node:fs';import {createHash} from 'node:crypto';
const sources=['tracking.mjs','machine-core.mjs','worker-core.mjs'].map(name=>[name,readFileSync(new URL(name,import.meta.url),'utf8')]);
const code=sources.map(([name,text])=>`// ${name}\n`+text.replace(/^import .*;\r?\n/gm,'').replace(/^export \{[^\n]+\n/gm,'')).join('\n');
const codeHash=createHash('sha256').update(code).digest('hex');
writeFileSync(new URL('browser-engine.mjs',import.meta.url),`// Generated by build-browser.mjs. Do not hand-edit.\n${code}\nexport const codeHash='${codeHash}';\n`);
