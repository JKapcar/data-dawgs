import fs from "node:fs/promises";

const season = Number(process.argv[2] || new Date().getUTCFullYear());
const asOf = process.argv[3] || new Date().toISOString().slice(0, 10);
const output = new URL("../bozo-team-registry.mjs", import.meta.url);
const sources = {
  cfb: `https://sports.core.api.espn.com/v2/sports/football/leagues/college-football/seasons/${season}/types/2/groups/80/teams?limit=200`,
  nfl: `https://sports.core.api.espn.com/v2/sports/football/leagues/nfl/seasons/${season}/teams?limit=100`,
};

async function getJson(url) {
  const response = await fetch(url, { headers: { accept: "application/json" } });
  if (!response.ok) throw new Error(`${response.status} ${url}`);
  return response.json();
}

async function fetchLeague(url) {
  const index = await getJson(url);
  const refs = (index.items || []).map((item) => String(item.$ref || "").replace(/^http:/, "https:"));
  if (!refs.length) throw new Error(`ESPN returned no team references for ${url}`);

  const teams = [];
  for (let offset = 0; offset < refs.length; offset += 20) {
    const batch = await Promise.all(refs.slice(offset, offset + 20).map(getJson));
    teams.push(...batch.map((team) => ({
      id: String(team.id || ""),
      abbreviation: String(team.abbreviation || ""),
      displayName: String(team.displayName || ""),
      shortDisplayName: String(team.shortDisplayName || ""),
      location: String(team.location || ""),
    })));
  }
  return teams.sort((a, b) => a.abbreviation.localeCompare(b.abbreviation) || a.id.localeCompare(b.id));
}

const sports = {};
for (const [sport, url] of Object.entries(sources)) sports[sport] = await fetchLeague(url);

const payload = { schemaVersion: 1, asOf, season, sources, sports };
const text = [
  "// Generated by tools/build-bozo-team-registry.mjs. Do not hand-edit.",
  `export const BOZO_ESPN_TEAM_SEED = ${JSON.stringify(payload, null, 2)};`,
  "",
].join("\n");
await fs.writeFile(output, text);
console.log(JSON.stringify({ output: output.pathname, counts: Object.fromEntries(
  Object.entries(sports).map(([sport, teams]) => [sport, teams.length])) }));
